# -*- coding: utf-8 -*-
"""별내신일유토빌: 등기부 122.759 -> 전용면적 122.75 매칭 시 일반 79000/하위 77000 확인"""
import sys
import os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from KB_api.kb_price_api import KBPriceAPI

# 별내신일유토빌 매매 (API 응답 일부)
별내신일유토빌_매매 = [
    {"공급면적": "131.58", "전용면적": "104.80", "하위평균": "69000", "일반평균": "73000", "상위평균": "75000"},
    {"공급면적": "154.20", "전용면적": "123.07", "하위평균": "77000", "일반평균": "79000", "상위평균": "82000"},
    {"공급면적": "155.15", "전용면적": "122.75", "하위평균": "77000", "일반평균": "79000", "상위평균": "82000"},
    {"공급면적": "180.77", "전용면적": "143.16", "하위평균": "83000", "일반평균": "85000", "상위평균": "87000"},
]

api = KBPriceAPI()
등기부_면적 = 122.759
matched = api.find_matching_price(별내신일유토빌_매매, 등기부_면적)

def run():
    assert matched is not None, "면적 매칭 결과가 None입니다."
    일반 = matched.get("일반평균")
    하위 = matched.get("하위평균")
    전용 = matched.get("전용면적")
    assert str(일반) == "79000", f"일반평균 기대 79000, 실제 {일반}"
    assert str(하위) == "77000", f"하위평균 기대 77000, 실제 {하위}"
    assert str(전용) == "122.75", f"전용면적 122.75 행이 선택돼야 함, 선택된 행 전용면적 {전용}"
    print("OK: 전용면적 122.75 매칭 -> 일반평균 79000, 하위평균 77000")

if __name__ == "__main__":
    run()
